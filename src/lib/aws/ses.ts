function p(text: string): string {
    return `<p style="color: #a1a1aa; font-size: 15px; line-height: 1.6; margin-bottom: 16px;">${text}</p>`;
}

function strong(text: string): string {
    return `<strong style="color: #eee;">${text}</strong>`;
}

function muted(text: string): string {
    return `<p style="color: #71717a; font-size: 13px; line-height: 1.5; margin-bottom: 0;">${text}</p>`;
}

function badge(label: string, color: string = '#F54029'): string {
    return `<span style="display: inline-block; padding: 4px 12px; background-color: ${color}22; color: ${color}; border: 1px solid ${color}44; border-radius: 6px; font-size: 12px; font-weight: 700; text-transform: uppercase; letter-spacing: 1px;">${label}</span>`;
}

// ============================================================================
// CORE SEND
// ============================================================================

export async function sendEmail(to: string, subject: string, htmlBody: string): Promise<{ success: boolean; error?: string }> {
    try {
        const command = new SendEmailCommand({
            Destination: { ToAddresses: [to] },
            Message: {
                Body: { Html: { Charset: "UTF-8", Data: htmlBody } },
                Subject: { Charset: "UTF-8", Data: subject }
            },
            Source: FROM_ADDRESS
        });

        const response = await sesClient.send(command);
        console.log(`Email sent to ${to}. Message ID:`, response.MessageId);
        return { success: true };
    } catch (error: any) {
        console.error(`Failed to send email to ${to}:`, error);
        return { success: false, error: error.message || String(error) };
    }
}

/** Fire-and-forget bulk email sender for sets of recipients */
export async function sendBulkEmails(
    recipients: Set<string> | string[],
    subjectFn: (email: string) => string,
    htmlFn: (email: string) => string
): Promise<void> {
    const emails = Array.from(recipients);
    for (const email of emails) {
        sendEmail(email, subjectFn(email), htmlFn(email)).catch(err =>
            console.error(`[SES Bulk] Failed for ${email}:`, err)
        );
    }
}

