export async function sendPasswordResetEmail(to: string, token: string) {
    const fallbackUrl = process.env.NEXT_PUBLIC_SITE_URL || 'https://theutilitycompany.co';
    const baseUrl = process.env.NEXT_PUBLIC_APP_URL || fallbackUrl;
    const resetUrl = token.startsWith('http') ? token : `${baseUrl}/nexus/reset-password?token=${token}`;

    const subject = "Password Reset requested for TUC Nexus";

    const ctaHtml = `<div style="text-align: center; margin: 32px 0;">
        <a href="${resetUrl}" style="display: inline-block; padding: 14px 36px; background: linear-gradient(135deg, #F54029 0%, #C53020 100%); color: #ffffff; text-decoration: none; border-radius: 8px; font-weight: 600; font-size: 15px; box-shadow: 0 4px 14px rgba(245,64,41,0.3);">Reset Password</a>
    </div>`;

    const body = buildEmailHtml(
        'Reset your password',
        p(`We received a request to reset the password for your TUC Nexus account associated with ${strong(to)}. You can securely configure a new password by clicking the button below.`) +
        ctaHtml +
        muted('If you did not request this password reset, your account is perfectly safe. You can safely ignore this message. For security, this reset link will automatically expire in 2 hours.')
    );

    return sendEmail(to, subject, body);
}

